    |
    */

    'retention' => [
        'days' => (int) env('BACKUP_RETENTION_DAYS', 30),
    ],

    /*
    |--------------------------------------------------------------------------
    | Downloads
    |--------------------------------------------------------------------------
    |
    | Lifetime (in minutes) of the temporary download URLs generated by
    | backup()->list() and `backup:list --url`. Only disks whose driver can
