    'path' => env('BACKUP_PATH', 'backups'),

    /*
    |--------------------------------------------------------------------------
    | Database
    |--------------------------------------------------------------------------
    |
    | The connection to dump (null = the app's default connection) and an
    | optional directory containing the dump binaries (mysqldump, pg_dump,
