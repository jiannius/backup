    |
    */

    'database' => [
        'connection' => null,
        'binary_path' => null,
    ],

    /*
    |--------------------------------------------------------------------------
    | Files
    |--------------------------------------------------------------------------
    |
    | Absolute folder paths to include in the archive, and glob patterns
